import { useRef, useState } from 'react';
import { PageHead } from '../components/common';
import { IconMic } from '../components/Icons';
import { weakest } from '../lib/srs';
import { recognitionCapabilities, startRecognition } from '../services/speech';
import { askTutor, tutorConfigured, type TutorMessage } from '../services/tutor';
import { useCourse } from '../state/course';
import { store, useSettings } from '../state/store';

const SCENARIOS = ['Meeting someone new at a family dinner', 'Ordering food at a restaurant', 'Talking with a friend about weekend plans', 'Asking for directions in a bazaar', 'A phone call to book an appointment'];

export function TutorPage() {
  const { idx } = useCourse();
  const settings = useSettings();
  const [scenario, setScenario] = useState(SCENARIOS[0]);
  const [level, setLevel] = useState(1);
  const [messages, setMessages] = useState<TutorMessage[]>([]);
  const [draft, setDraft] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [listening, setListening] = useState(false);
  const caps = recognitionCapabilities();
  const abortRef = useRef<AbortController | null>(null);

  if (!tutorConfigured()) {
    return (
      <>
        <PageHead title="AI tutor" backTo="/talk" />
        <div className="card stack">
          <strong>The AI tutor isn't set up for this copy of Leni Urdu Class.</strong>
          <p className="muted" style={{ margin: 0 }}>
            It needs a small server that keeps an AI provider key private (never in the browser). The project includes one in <code>server/tutor-proxy.mjs</code>; the
            README explains how to run it and point the app at it.
          </p>
          <p className="muted" style={{ margin: 0 }}>
            Everything else — lessons, scripted conversations and speaking practice — works without it.
          </p>
          <a className="btn primary" href="#/talk">
            Try a scripted conversation
          </a>
        </div>
      </>
    );
  }

  const send = async (text: string) => {
    const t = text.trim();
    if (!t || busy) return;
    const next = [...messages, { role: 'user' as const, content: t }];
    setMessages(next);
    setDraft('');
    setBusy(true);
    setError(null);
    abortRef.current = new AbortController();
    try {
      const difficulties = weakest(Object.values(store.getState().cards), 5)
        .map((c) => idx.phraseById.get(c.id)?.roman)
        .filter((x): x is string => !!x);
      const r = await askTutor({ scenario, level, difficulties, messages: next }, abortRef.current.signal);
      setMessages([...next, { role: 'assistant', content: r.text }]);
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  };

  const speak = () => {
    if (settings.recognitionConsent !== 'granted') {
      setError('Turn on speech recognition in Settings → Speaking to talk to the tutor by voice.');
      return;
    }
    setListening(true);
    startRecognition({
      lang: settings.recognitionLang,
      onResult: (alts) => {
        setListening(false);
        if (alts[0]) setDraft(alts[0]);
        else setError("We couldn't recognize that. Try again or type your reply.");
      },
      onError: () => {
        setListening(false);
        setError('Speech recognition failed — you can type instead.');
      },
    });
  };

  return (
    <>
      <PageHead title="AI tutor" backTo="/talk" />
      <p className="small muted" style={{ marginTop: -8 }}>
        Replies are generated by an AI model through your tutor server and can contain mistakes. Your messages are sent to that server.
      </p>
      {messages.length === 0 && (
        <div className="card soft stack">
          <label>
            <strong>Scenario</strong>
            <select className="search" value={scenario} onChange={(e) => setScenario(e.target.value)}>
              {SCENARIOS.map((s) => (
                <option key={s}>{s}</option>
              ))}
            </select>
          </label>
          <label>
            <strong>Level</strong>
            <select className="search" value={level} onChange={(e) => setLevel(Number(e.target.value))}>
              {[1, 2, 3, 4, 5, 6].map((l) => (
                <option key={l} value={l}>
                  Level {l}
                </option>
              ))}
            </select>
          </label>
          <p className="small muted" style={{ margin: 0 }}>
            Start by greeting the tutor, e.g. "Assalamu alaikum!"
          </p>
        </div>
      )}
      <div className="dialogue" style={{ marginTop: 12 }} aria-live="polite">
        {messages.map((m, i) => (
          <div key={i} className={`bubble ${m.role === 'user' ? 'me' : 'them'}`} style={{ whiteSpace: 'pre-wrap' }}>
            <div className="who">{m.role === 'user' ? 'You' : 'Tutor (AI)'}</div>
            {m.content}
          </div>
        ))}
        {busy && <div className="bubble them muted">Tutor is replying…</div>}
      </div>
      {error && (
        <p className="banner" role="alert">
          {error}
        </p>
      )}
      <form
        className="row"
        onSubmit={(e) => {
          e.preventDefault();
          void send(draft);
        }}
      >
        <label className="sr-only" htmlFor="tutor-input">
          Your reply
        </label>
        <input id="tutor-input" className="search grow" value={draft} onChange={(e) => setDraft(e.target.value)} placeholder="Type in Roman Urdu or English" lang="ur-Latn" />
        {caps.supported && (
          <button type="button" className={`icon-btn ${listening ? 'live' : ''}`} onClick={speak} aria-label="Speak your reply" disabled={listening}>
            <IconMic />
          </button>
        )}
        <button className="btn primary" disabled={busy || !draft.trim()}>
          Send
        </button>
      </form>
      {messages.length > 0 && (
        <button
          className="btn small ghost"
          style={{ marginTop: 10 }}
          onClick={() => {
            abortRef.current?.abort();
            setMessages([]);
          }}
        >
          New conversation
        </button>
      )}
    </>
  );
}
